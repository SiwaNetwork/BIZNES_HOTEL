"""АБВГ.464512.001 Э1 — схема электрическая структурная (ГОСТ 2.701-2008, ГОСТ 2.702-2011)."""
from reportlab.lib import colors
from reportlab.pdfgen import canvas
from reportlab.lib.units import mm

import gost
from gost import Pen, S

LW_BLOCK = 0.5
LW_LINE = 0.35


def block(p: Pen, x, y, w, h, title, params=(), ref=None, dashed=False):
    p.rect(x, y, w, h, LW_BLOCK, dash=(4, 1.5) if dashed else None)
    lines = [(s, 3.5) for s in title.split("\n")] + [(s, 2.5) for s in params]
    total = sum(hh * 1.75 for _, hh in lines)
    yy = y + h / 2 + total / 2 - 3.5
    for s, hh in lines:
        p.text(x + w / 2, yy, s, p.fit(s, w - 3, hh), "c")
        yy -= hh * 1.75
    if ref:
        p.text(x + 1.2, y + h - 4, ref, 2.5)


def antenna(p: Pen, x, y):
    """Условное графическое обозначение антенны (ГОСТ 2.735)."""
    p.line(x, y, x, y + 16, LW_LINE)
    p.line(x - 6, y + 16, x, y + 8, LW_LINE)
    p.line(x + 6, y + 16, x, y + 8, LW_LINE)
    p.line(x - 6, y + 16, x + 6, y + 16, LW_LINE)


def poly(p: Pen, pts, arrow=True, w=LW_LINE, dash=None):
    for (x1, y1), (x2, y2) in zip(pts[:-2], pts[1:-1]):
        p.line(x1, y1, x2, y2, w, dash)
    (x1, y1), (x2, y2) = pts[-2], pts[-1]
    if arrow:
        p.arrow(x1, y1, x2, y2, w, 3)
    else:
        p.line(x1, y1, x2, y2, w, dash)


def dot(p: Pen, x, y):
    p.circle(x, y, 0.6, 0.2, fill=colors.black)


def build(path):
    W, H = gost.A3L
    c = canvas.Canvas(str(path), pagesize=(W * mm, H * mm))
    c.setTitle(f"{gost.CODE} Э1 — Схема электрическая структурная")
    c.setAuthor("Технический проект")
    p = Pen(c)
    gost.frame(p, W, H, drawing=True, code=gost.CODE + " Э1")

    # --- антенна и антенный коммутатор
    antenna(p, 40, 199)
    p.text(40, 219, "WA1", 3.5, "c")
    p.line(40, 199, 46, 199, LW_LINE)
    p.arrow(46, 199, 52, 199, LW_LINE, 3, both=True)
    block(p, 52, 182, 40, 34, "Антенный\nкоммутатор", ("ПР/ПД, Pвх до 33 дБм", "перестройка согласования WA1"), "A1")

    # --- тракт передачи (верх)
    block(p, 108, 228, 44, 30, "Фильтр\nполосовой ПД", ("1626,5–1660,5 МГц",), "Z1")
    block(p, 166, 228, 50, 30, "Усилитель\nмощности", ("Pвых 20…30 дБм, КПД ≥ 40 %", "детектор мощности"), "A2")
    # --- тракт приёма (низ)
    block(p, 108, 140, 44, 30, "Фильтр\nполосовой ПР", ("1525–1559 МГц",), "Z2")
    block(p, 166, 140, 50, 30, "Малошумящий\nусилитель", ("Кш ≤ 1 дБ, Ку ≥ 18 дБ",), "A3")
    # --- приёмопередатчик
    block(p, 232, 132, 46, 134, "Приёмопередатчик\nРЧ", (
        "квадратурный", "модулятор/демодулятор,", "синтезатор частот,", "АЦП/ЦАП I/Q", "", "1,5–1,7 ГГц"), "A4")
    # --- микроконтроллер-модем
    block(p, 296, 132, 50, 134, "Микроконтроллер-\nмодем", (
        "ЦОС: π/2-BPSK, OQPSK,", "LDPC/турбокод,", "протокол канального", "уровня, шифрование,",
        "управление режимами,", "контроль температуры"), "A5")
    block(p, 296, 272, 50, 16, "Память", ("буфер сообщений, ПО",), "A6")
    # --- соединитель и внешние устройства
    p.rect(356, 100, 8, 166, LW_BLOCK)
    p.text(360, 268, "X1", 3.5, "c")
    block(p, 374, 192, 38, 60, "Полётный\nконтроллер\nБПЛА", ("(внешнее", "устройство)"), dashed=True)
    block(p, 374, 92, 38, 30, "АКБ Li-Ion\n1S 3,7 В", ("(внешнее", "устройство)"), dashed=True)
    # --- опорный генератор и питание
    block(p, 232, 96, 46, 26, "Опорный\nгенератор", ("ТСХО 26 МГц, ±0,5 ppm",), "G1")
    block(p, 60, 72, 160, 40, "Узел питания", (
        "ключ питания УМ, накопитель энергии ≥ 440 мкФ,",
        "стабилизатор импульсный 1,8 В, стабилизаторы линейные 3,0 В (РЧ),",
        "контроль напряжения АКБ, защита от переполюсовки"), "A7")

    # --- связи РЧ-тракта
    poly(p, [(232, 243), (216, 243)])                     # A4 -> A2
    poly(p, [(166, 243), (152, 243)])                     # A2 -> Z1
    poly(p, [(108, 243), (82, 243), (82, 216)])           # Z1 -> A1
    poly(p, [(82, 182), (82, 155), (108, 155)])           # A1 -> Z2
    poly(p, [(152, 155), (166, 155)])                     # Z2 -> A3
    poly(p, [(216, 155), (232, 155)])                     # A3 -> A4
    p.text(224, 245, "ПД", 2.5, "c")
    # детектор мощности -> A5 (обратная связь), обход A4 сверху
    poly(p, [(191, 258), (191, 270), (288, 270), (288, 252), (296, 252)])
    p.text(240, 271.6, "уровень мощности", 2.5, "c")
    # управление коммутатором и МШУ
    poly(p, [(296, 140), (288, 140), (288, 126), (100, 126), (100, 199), (92, 199)])
    p.text(150, 127.6, "ПР/ПД (управление коммутатором)", 2.5, "c")
    poly(p, [(205, 126), (205, 140)])
    dot(p, 205, 126)
    p.text(207, 131, "вкл. МШУ", 2.5)
    # A4 <-> A5
    p.arrow(278, 220, 296, 220, LW_LINE, 3, both=True)
    p.text(287, 222, "I/Q", 2.5, "c")
    p.arrow(278, 200, 296, 200, LW_LINE, 3, both=True)
    p.text(287, 202, "SPI", 2.5, "c")
    p.arrow(296, 180, 278, 180, LW_LINE, 3)
    p.text(287, 182, "упр.", 2.5, "c")
    # A5 <-> A6
    p.arrow(321, 266, 321, 272, LW_LINE, 2.5, both=True)
    # G1 -> A4, A5
    poly(p, [(255, 122), (255, 132)])
    poly(p, [(278, 109), (321, 109), (321, 132)])
    p.text(300, 111, "26 МГц", 2.5, "c")
    # A5 <-> X1 <-> полётный контроллер
    for name, yy in (("UART", 244), ("WAKE", 230), ("IRQ", 216), ("PPS", 202)):
        if name == "UART":
            p.arrow(346, yy, 356, yy, LW_LINE, 2.5, both=True)
            p.arrow(364, yy, 374, yy, LW_LINE, 2.5, both=True)
        elif name == "IRQ":
            p.arrow(346, yy, 356, yy, LW_LINE, 2.5)
            p.arrow(364, yy, 374, yy, LW_LINE, 2.5)
        else:
            p.arrow(356, yy, 346, yy, LW_LINE, 2.5)
            p.arrow(374, yy, 364, yy, LW_LINE, 2.5)
        p.text(351, yy + 1.5, name, 2.0, "c")
    # питание: АКБ -> X1 -> A7
    poly(p, [(374, 107), (364, 107)])
    p.line(356, 107, 350, 107, LW_LINE)
    poly(p, [(350, 107), (350, 86), (220, 86)])
    p.text(369, 109, "+VBAT", 2.0, "c")
    p.text(285, 88, "+VBAT 3,3…4,2 В", 2.5, "c")
    # шины питания (штриховые)
    d = (2, 1)
    poly(p, [(160, 112), (160, 236), (166, 236)], w=0.25, dash=d)          # +VPA -> A2
    p.text(161.5, 118, "+VPA", 2.5)
    poly(p, [(205, 112), (205, 114), (226, 114), (226, 140)], arrow=False, w=0.25, dash=d)
    p.line(226, 140, 226, 148, 0.25, d)
    poly(p, [(226, 148), (216, 148)], w=0.25, dash=d)                     # -> A3
    poly(p, [(226, 140), (232, 140)], w=0.25, dash=d)                     # -> A4
    poly(p, [(226, 114), (232, 114)], w=0.25, dash=d)                     # -> G1
    p.text(207, 115.6, "+3,0 В", 2.5)
    poly(p, [(100, 72), (100, 66), (330, 66), (330, 132)], w=0.25, dash=d)  # -> A5, A6
    p.text(300, 67.6, "+1,8 В", 2.5)
    p.text(222, 157, "ПР", 2.5, "c")

    # --- примечания и таблица характеристик
    notes = [
        "Схема структурная. Параметры функциональных частей ориентировочные, уточняются на стадии рабочего проекта.",
        "Сплошные линии со стрелками — направление прохождения сигналов; штриховые — цепи питания.",
        "Штриховые рамки — внешние устройства, в состав модуля не входят.",
        "Частотные диапазоны указаны для подвижной спутниковой службы L-диапазона; при выборе S-диапазона "
        "(1980–2010/2170–2200 МГц) изменяются Z1, Z2, A2, A3 и антенна WA1.",
        "Интерфейс X1: краевые полуотверстия (castellated), шаг 2,54 мм, 20 контактов; разъём антенный — "
        "коаксиальный малогабаритный 50 Ом.",
    ]
    p.text(26, 52, "Примечания", 3.5)
    y = 46
    from reportlab.lib.utils import simpleSplit
    for i, s in enumerate(notes, 1):
        for j, ln in enumerate(simpleSplit(f"{i} {s}", "GOST", gost.fs(2.5), 196 * mm)):
            p.text(26 + (0 if j == 0 else 3), y, ln, 2.5)
            y -= 4.4
    gost.stamp_form1(p, W, gost.PRODUCT, "Схема электрическая структурная",
                     code=gost.CODE + " Э1", lit="Т", sheet="", sheets="1")
    c.showPage()
    c.save()


if __name__ == "__main__":
    import sys
    gost.register_fonts()
    build(sys.argv[1] if len(sys.argv) > 1 else "e1.pdf")
