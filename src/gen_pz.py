class StampCanvas(rl_canvas.Canvas):
    """Откладывает отрисовку рамок до save(), чтобы знать общее число листов."""

    def __init__(self, *a, **kw):
        super().__init__(*a, **kw)
        self._pages = []

    def showPage(self):
        self._pages.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        total = len(self._pages)
        for i, st in enumerate(self._pages, 1):
            self.__dict__.update(st)
            self._decorate(i, total)
            super().showPage()
        super().save()

    def _decorate(self, n, total):
        W, H = gost.A4
        p = Pen(self)
        self.saveState()
        if n == 1:
            # титульный лист: без рамки и основной надписи, с графами 19–23 (ГОСТ 2.105, ГОСТ 2.104)
            gost.margin_graphs(p)
            self.setFont("Serif", 14)
            self.drawCentredString(112.5 * mm, 134 * mm, f"Листов {total}")
        elif n == 2:
            gost.frame(p, W, H, drawing=False, first=True, code=CODE)
            gost.stamp_form2(p, W, gost.PRODUCT, DOCNAME, code=CODE, lit="Т", sheet=n, sheets=total)
        else:
            gost.frame(p, W, H, drawing=False, first=False, code=CODE)
            gost.stamp_form2a(p, W, n, code=CODE)
        self.restoreState()


